# One-time local database setup (safe to re-run):
#   - initialises a Postgres cluster under %LOCALAPPDATA%\TechOasis\pgdata
#   - creates the techoasis_sms database and its dedicated login role
#   - writes generated credentials to .env.local (git-ignored), never to the console
#   - applies supabase/migrations
. "$PSScriptRoot\common.ps1"

if (-not (Test-Path "$PgBin\pg_ctl.exe")) { throw "Postgres binaries not found in $PgBin" }

$envVars = Read-EnvFile
$adminPw = if ($envVars['DATABASE_ADMIN_URL'] -match '^postgres(ql)?://postgres:([^@]+)@') { $Matches[2] } else { New-Secret }
$appPw   = if ($envVars['DATABASE_URL'] -match '^postgres(ql)?://techoasis_app:([^@]+)@') { $Matches[2] } else { New-Secret }

if (-not (Test-Path (Join-Path $PgData 'PG_VERSION'))) {
  $pwFile = [IO.Path]::GetTempFileName()
  try {
    Set-Content -Path $pwFile -Value $adminPw -NoNewline -Encoding ascii
    & "$PgBin\initdb.exe" -D $PgData -U postgres --pwfile=$pwFile --auth=scram-sha-256 -E UTF8 --locale=C | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'initdb failed' }
  } finally { Remove-Item $pwFile -Force }
  Write-Host "Initialised Postgres cluster at $PgData"
}

$adminUrl = "postgresql://postgres:$adminPw@localhost:$PgPort/postgres"
$appUrl   = "postgresql://techoasis_app:$appPw@localhost:$PgPort/techoasis_sms"

# Persist credentials before using them so a failed run can be resumed.
$keep = @()
if (Test-Path $EnvFile) {
  $keep = Get-Content $EnvFile | Where-Object { $_ -notmatch '^\s*(DATABASE_URL|DATABASE_ADMIN_URL|VITE_DB_PROVIDER)\s*=' -and $_ -notmatch '^# Local database' }
}
$lines = @(
  '# Local database (generated by scripts/local-db/setup.ps1 - do not commit)'
  'VITE_DB_PROVIDER=local'
  "DATABASE_URL=$appUrl"
  "DATABASE_ADMIN_URL=$adminUrl"
) + $keep
Set-Content -Path $EnvFile -Value $lines -Encoding ascii

Start-Pg

$roleSql = @"
DO `$`$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'techoasis_app') THEN
    CREATE ROLE techoasis_app LOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'web_anon') THEN
    CREATE ROLE web_anon NOLOGIN;
  END IF;
  -- Same request roles as Supabase: signed-out (anon) and signed-in (authenticated).
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN;
  END IF;
END `$`$;
ALTER ROLE techoasis_app WITH LOGIN PASSWORD '$appPw';
GRANT web_anon, anon, authenticated TO techoasis_app;
"@
# Feed SQL on stdin so the password never appears in a process command line.
$roleSql | & "$PgBin\psql.exe" -X -q -v ON_ERROR_STOP=1 -d $adminUrl | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Creating roles failed' }

$dbExists = & "$PgBin\psql.exe" -X -q -t -A -d $adminUrl -c "SELECT 1 FROM pg_database WHERE datname = 'techoasis_sms'"
if ($dbExists -ne '1') {
  Invoke-Psql $adminUrl @('-c', 'CREATE DATABASE techoasis_sms OWNER techoasis_app')
  Write-Host 'Created database techoasis_sms'
}

& "$PSScriptRoot\migrate.ps1"
Write-Host "Done. Credentials are in $EnvFile"
